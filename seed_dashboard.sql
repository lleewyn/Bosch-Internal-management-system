    SELECT COALESCE(SUM(ep.revenue_amount), 0)
    FROM effort_projects ep
    JOIN project_assignments pa ON ep.assignment_id = pa.assignment_id
    JOIN project_resource_requests prr ON pa.project_resource_request_id = prr.project_resource_request_id
    WHERE prr.project_id = projects.project_id
)
